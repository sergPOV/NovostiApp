// ============================================================
// ОПРЕДЕЛЕНИЕ КАТЕГОРИИ
// ============================================================
export const getCategoryKey = (title = '', excerpt = '') => {
  const text = `${title || ''} ${excerpt || ''}`.toLowerCase();

  const found = CATEGORY_RULES.find(({ words }) =>
    words.some((word) => text.includes(word))
  );

  return found ? found.key : 'all';
};

// ============================================================
// ПОЛУЧЕНИЕ ИНФОРМАЦИИ О КАТЕГОРИИ
// ============================================================
export const getCategoryInfo = (title = '', excerpt = '') => {
  const key = getCategoryKey(title, excerpt);

  const defaultCategory = {
    key: 'all',
    icon: '📰',
    label: 'Все',
    color: '#607D8B',
  };

  const found = CATEGORY_RULES.find((rule) => rule.key === key);
  return found || defaultCategory;
};

